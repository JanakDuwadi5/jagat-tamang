<script setup>
import { ref, reactive, onMounted, watch } from 'vue'
import { useRoute } from 'vue-router'

const route = useRoute()

const form = reactive({
  name: '',
  email: '',
  subject: 'commission',
  painting: '',
  message: '',
  consent: false,
})

const errors = reactive({})
const sending = ref(false)
const submitted = ref(false)
const submitError = ref('')

const syncFromRoute = () => {
  const queryType = route.query.type || route.state?.type || route.state?.subject
  if (queryType) {
    if (['commission', 'acquisition', 'exhibition', 'studio', 'general'].includes(queryType)) {
      form.subject = queryType
    }
  } else {
    form.subject = 'commission'
  }

  const queryPainting = route.query.painting || route.state?.painting
  if (queryPainting) {
    form.painting = queryPainting
    if (!queryType) {
      form.subject = 'acquisition'
    }
  }
}

onMounted(() => {
  syncFromRoute()
})

watch(
  () => [route.query, route.state],
  () => {
    syncFromRoute()
  },
  { deep: true },
)

const validate = () => {
  Object.keys(errors).forEach((k) => delete errors[k])
  let valid = true
  if (!form.name.trim()) {
    errors.name = 'Please provide your full name.'
    valid = false
  }
  if (!form.email.trim() || !/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(form.email)) {
    errors.email = 'Please provide a valid email address.'
    valid = false
  }
  if (!form.message.trim() || form.message.trim().length < 10) {
    errors.message = 'Please share a brief message regarding your inquiry (at least 10 characters).'
    valid = false
  }
  if (!form.consent) {
    errors.consent = 'Please confirm consent to proceed.'
    valid = false
  }
  return valid
}

const handleSubmit = async () => {
  if (!validate()) return
  sending.value = true
  submitError.value = ''
  try {
    await new Promise((r) => setTimeout(r, 1200))
    submitted.value = true
  } catch {
    submitError.value =
      'An error occurred while sending your message. Please reach out via email directly.'
  } finally {
    sending.value = false
  }
}
</script>

